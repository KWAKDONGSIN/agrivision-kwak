d.p('4×4 = 16칸짜리 아주 작은 사진이 있습니다. ●는 블루베리, ·는 배경입니다.')
d.code('''정답(마스크)          예측(모델이 낸 답)
 · · · ·               · · · ·
 · ● ● ·               · ● ● ●
 · ● ● ·               · ● ● ·
 · · · ·               · · · ·

 정답 블루베리 = 4칸      예측 블루베리 = 5칸''')
d.p('**풀이:**')
d.bullets([
    'TP (둘 다 ●) = 4칸',
    'FP (예측만 ●) = 1칸 (오른쪽 위로 하나 튀어나온 것)',
    'FN (정답만 ●) = 0칸',
    '**IoU = 4 ÷ (4 + 1 + 0) = 4/5 = 0.80**',
    '**Dice = (2×4) ÷ (2×4 + 1 + 0) = 8/9 ≈ 0.889**',
    'Precision = 4 ÷ 5 = 0.80  /  Recall = 4 ÷ 4 = **1.00**',
])
d.note('Recall이 1.00인데 Precision이 0.80입니다. 놓친 건 없지만 헛짚은 게 있다는 뜻입니다. '
       '그리고 Dice(0.889)가 IoU(0.80)보다 항상 큽니다.')

