def u16(p):
    a = np.array(Image.open(p))
    return (a[:, :, 0] if a.ndim == 3 else a).astype(np.int32)


# ── 그림 1: 사과 번호 마스크 → 번호마다 상자 하나 (툴의 «마스크에서 초벌 생성» 과 같은 규칙: 4화소 미만 번호 제외)
def fig_apple():
    stem = '20150919_174151_image1'
    img = np.array(Image.open(STD / 'apple/images' / (stem + '.png')).convert('RGB'))
    inst = u16(STD / 'apple/masks' / (stem + '.png'))
    ids = [i for i in np.unique(inst) if i > 0]
    boxes = [(i, sl) for i, sl in enumerate(ndimage.find_objects(inst), 1)
             if sl is not None and (inst[sl] == i).sum() >= 4]
    rng = np.random.RandomState(0)
    pal = rng.randint(60, 255, (inst.max() + 1, 3)); pal[0] = 0
    over = img.copy(); m = inst > 0
    over[m] = (0.45 * img[m] + 0.55 * pal[inst[m]]).astype(np.uint8)
    f, ax = plt.subplots(1, 3, figsize=(15, 9.2))
    for a, im, t in zip(ax, [img, over, img], ['원본 사진', '열매 번호 레이어 (번호 %d개)' % len(ids), '번호마다 상자 하나 (상자 %d개)' % len(boxes)]):
        a.imshow(im); a.set_title(t, fontsize=15, fontproperties=REG); a.axis('off')
    for _, (ys, xs) in boxes:
        ax[2].add_patch(plt.Rectangle((xs.start, ys.start), xs.stop - xs.start, ys.stop - ys.start, fill=False, ec='#00e5ff', lw=1.2))
    f.tight_layout(); p = FIG / 'fig1_apple_numbers_boxes.png'; f.savefig(p, dpi=110); plt.close(f)
    return p, len(ids), len(boxes)


# ── 그림 2: 블루베리 (144)_121 — 이진 마스크에는 있는데 검출 팀 초벌 번호가 없는 자리(N6 이 지우던 화소)
def fig_blueberry():
    stem = 'Camera 1 Video (144)_121'
    img = np.array(Image.open(STD / 'blueberry/images' / (stem + '.png')).convert('RGB'))
    mb = u16(STD / 'blueberry/masks' / (stem + '.png')) > 0
    seed = u16(PARK / 'bbox_outputs/blueberry/all/instance_maps' / (stem + '.png'))
    hole = mb & (seed == 0)
    over = img.copy(); over[mb] = (0.5 * img[mb] + 0.5 * np.array([60, 120, 255])).astype(np.uint8)
    over[ndimage.binary_dilation(hole, iterations=3)] = [255, 40, 40]
    f, ax = plt.subplots(1, 2, figsize=(14, 7.5))
    ax[0].imshow(img); ax[0].set_title('원본 사진', fontsize=15, fontproperties=REG)
    ax[1].imshow(over); ax[1].set_title('파랑 = 마스크 전경 · 빨강 = 번호가 없는 전경 %d화소 (보이게 굵게 칠함)' % hole.sum(), fontsize=13, fontproperties=REG)
    for a in ax: a.axis('off')
    f.tight_layout(); p = FIG / 'fig2_blueberry_hole.png'; f.savefig(p, dpi=110); plt.close(f)
    return p, int(hole.sum()), int(len(np.unique(seed)) - 1)


