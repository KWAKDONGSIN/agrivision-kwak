def mtime(p):
    p = Path(p)
    if not p.exists():
        return '없음'
    return datetime.fromtimestamp(p.stat().st_mtime).strftime('%m-%d %H:%M')


def size_mb(p):
    p = Path(p)
    return '-' if not p.exists() else f'{p.stat().st_size / 1e6:.1f}MB'


