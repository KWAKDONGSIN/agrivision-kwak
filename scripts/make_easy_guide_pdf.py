BENCH_HEADS = {'ccaseg', 'mask2former', 'oneformer', 'upernet'}   # 벤치마크 32조합의 헤더


def blueberry_top():
    """results_summary.csv 에는 벤치마크 밖의 헤더(bisenetv2, lightham)도 섞여 있으므로
    32조합에 해당하는 4개 헤더만 남긴다."""
    import csv
    p = REPO / 'output/results_summary.csv'
    if not p.exists():
        return []
    agg = defaultdict(list)
    with p.open() as f:
        for row in csv.DictReader(f):
            if row.get('head') not in BENCH_HEADS:
                continue
            try:
                agg[(row['head'], row['backbone'])].append(float(row['fg_IoU']))
            except (KeyError, ValueError):
                continue
    out = [(h, b, sum(v) / len(v), len(v)) for (h, b), v in agg.items() if v]
    return sorted(out, key=lambda x: -x[2])


