def f3(v, bold=False):
    s = f'{v:.3f}'
    return f'**{s}**' if bold else s


def table5_rows():
    """Table 5 를 pdfdoc 표 행으로. 최고/최저 칸은 굵게."""
    rows = []
    for head, vals, mean in TABLE5:
        cells = [f'**{head}**']
        for v in vals:
            cells.append(f3(v, bold=(v == 0.859 or v == 0.687)))
        cells.append(f3(mean, bold=(mean in (0.848, 0.769))))
        rows.append(cells)
    rows.append(['**백본 평균**'] + [f3(v, bold=(v in (0.835, 0.778))) for v in BB_MEAN] + [''])
    return rows


